// Copies ../contracts/deployments/*.json into src/deployments and generates src/deployments/index.ts,
// so the static build imports whichever chains have been deployed without a code change per chain.
import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "contracts", "deployments");
const dst = join(here, "..", "src", "deployments");
mkdirSync(dst, { recursive: true });

const chainIds = [];
if (existsSync(src)) {
  for (const f of readdirSync(src)) {
    const m = /^(\d+)\.json$/.exec(f);
    if (!m) continue;
    copyFileSync(join(src, f), join(dst, f));
    chainIds.push(m[1]);
  }
}
chainIds.sort((a, b) => Number(a) - Number(b));

const lines = [
  "// Generated by scripts/sync-deployments.mjs at build time; do not edit.",
  ...chainIds.map((id) => `import d${id} from "./${id}.json";`),
  "",
  "export const deployments: Record<number, unknown> = {",
  ...chainIds.map((id) => `  ${id}: d${id},`),
  "};",
  "",
];
writeFileSync(join(dst, "index.ts"), lines.join("\n"));
console.log(`deployments synced: ${chainIds.length ? chainIds.join(", ") : "none"}`);
