import { deployments as generated } from "@/deployments";

/** Generated by scripts/sync-deployments.mjs from contracts/deployments/*.json at build time. */
const deployments = generated as Record<number, DeploymentAddresses | undefined>;

export function addresses(): DeploymentAddresses {
  const d = deployments[CHAIN_ID];
  if (!d) throw new Error(`no deployment for chain ${CHAIN_ID}: run the deploy script and sync-deployments`);
  return d;
}

