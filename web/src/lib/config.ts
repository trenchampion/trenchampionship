/** Link to the standalone LaunchPool UI, pre-selecting this chain and pool. */
export function launchUiUrl(chainId: number, pool: string): string {
  const base = LAUNCH_UI_URL.replace(/\/$/, "");
  return `${base}/?chain=${chainId}&pool=${pool}`;
}

